INSERT INTO "Fiscal".jurisdictions (country_id, parent_id, level, code, external_code, name)
SELECT co.id, d.id, 'municipality', m.code, m.external_code, m.name
FROM m
CROSS JOIN co
JOIN "Fiscal".jurisdictions d
  ON d.country_id = co.id AND d.level = 'department' AND d.code = m.dept_code
ON CONFLICT ON CONSTRAINT uq_jurisdiction DO NOTHING;

